def _payloads() -> dict[str, bytes]:
    payloads = {"README.md": _README.encode("utf-8"),
                "EXPECTED.json": _json_bytes(_expectations())}
    captures = []
    for name, samples, raw_hex, raw_sha, _decoded_sha in _VECTORS:
        raw = struct.pack("<4f", *samples)
        if raw.hex() != raw_hex or _sha256(raw) != raw_sha:
            raise DemoError(f"literal original-byte identity mismatch for {name}")
        manifest = _json_bytes(_manifest(name, samples, raw))
        payloads[f"corpus/audio/{name}.f32"] = raw
        payloads[f"corpus/{name}.json"] = manifest
        captures.append({
            "capture_id": name, "manifest_path": f"{name}.json",
            "manifest_sha256": _sha256(manifest), "purpose": "validation",
            "relation_labels": [{"kind": "family", "label": "literal-offsets"}],
            "parent_capture_ids": [], "derived_audio": [],
        })
    corpus = _json_bytes({
        "schema_version": 1, "contract_origin": "project-proposed-corpus-v1",
        "corpus_id": "synthetic-offset-corpus", "captures": captures,
    })
    payloads["corpus/corpus.json"] = corpus
    jobs = []
    for label, candidate, bound, *_unused in _CASES:
        policy_path = f"policy-{label}.json"
        policy = _json_bytes(_policy(label, bound))
        payloads[policy_path] = policy
        job_path = f"job-{label}.json"
        job = _json_bytes({
            "schema_version": 1,
            "contract_origin": "project-proposed-capture-job-v1",
            "job_id": f"demo-{label}",
            "corpus": {"path": "corpus/corpus.json", "sha256": _sha256(corpus)},
            "reference": {"capture_id": "reference", "file_id": "raw", "start_frame": 0},
            "candidate": {"capture_id": candidate, "file_id": "raw", "start_frame": 0},
            "analysis": _analysis(),
            "policy": {"path": policy_path, "sha256": _sha256(policy)},
            "pairing": "index", "transform": "none",
        })
        payloads[job_path] = job
        jobs.append({"job_id": f"demo-{label}", "path": job_path, "sha256": _sha256(job)})
    payloads["study.json"] = _json_bytes({
        "schema_version": 1, "contract_origin": "project-proposed-capture-study-v1",
        "study_id": "synthetic-offset-demo", "corpus_sha256": _sha256(corpus), "jobs": jobs,
    })
    return payloads


def build_demo(output_dir: str | Path) -> dict:
    """Exclusively create all fixed inputs; preserve and disclose partial creation."""
    if not ((type(output_dir) is str and output_dir) or isinstance(output_dir, Path)):
        raise DemoError("output_dir must be an exact nonempty string or pathlib.Path")
    created = False
    try:
        target = Path(output_dir)
        payloads = _payloads()
        inventory = {
            "schema_version": 1,
            "contract_origin": "project-proposed-capture-demo-v1",
            "evidence_class": "synthetic_numerical_fixture", "execution": "not_run",
            "file_count": len(payloads),
            "total_size_bytes": sum(len(data) for data in payloads.values()),
            "files": [{"path": path, "size_bytes": len(payloads[path]),
                       "sha256": _sha256(payloads[path])} for path in sorted(payloads)],
            "physical_fidelity": "not_established", "permissions": "not_established",
        }
        target.mkdir(parents=False, exist_ok=False)
        created = True
        (target / "corpus").mkdir(parents=False, exist_ok=False)
        (target / "corpus" / "audio").mkdir(parents=False, exist_ok=False)
        for relative in sorted(payloads):
            with (target / relative).open("xb") as stream:
                if stream.write(payloads[relative]) != len(payloads[relative]):
                    raise OSError(f"incomplete write for {relative}")
        return inventory
    except (OSError, ValueError, TypeError, OverflowError) as exc:
        if created:
            raise DemoError(
                f"partial new demo creation retained at {output_dir}: {exc}") from exc
        raise DemoError(f"cannot create new demo at {output_dir}: {exc}") from exc


class _SingleOutput(argparse.Action):
    def __call__(self, parser, namespace, values, option_string=None):
        if getattr(namespace, self.dest) is not None:
            parser.error("--output may be supplied only once")
        if not values:
            parser.error("--output must be nonempty")
        setattr(namespace, self.dest, values)


def _write_stdout(payload: bytes) -> None:
    binary = getattr(sys.stdout, "buffer", None)
    if binary is not None:
        if binary.write(payload) != len(payload):
            raise OSError("incomplete inventory stdout write")
        binary.flush()
    else:
        decoded = payload.decode("utf-8")
        if sys.stdout.write(decoded) != len(decoded):
            raise OSError("incomplete inventory stdout write")
        sys.stdout.flush()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                     allow_abbrev=False)
    parser.add_argument("--output", required=True, action=_SingleOutput,
                        help="new demo directory; its parent must already exist")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return int(exc.code)
    try:
        inventory = build_demo(args.output)
    except DemoError as exc:
        print(f"demo error: {exc}", file=sys.stderr)
        return 1
    try:
        _write_stdout(_json_bytes(inventory))
    except (OSError, ValueError, TypeError, OverflowError) as exc:
        print(f"demo error: created demo retained at {args.output}; "
              f"inventory stdout publication failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
