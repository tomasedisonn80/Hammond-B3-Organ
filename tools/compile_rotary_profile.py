#!/usr/bin/env python3
"""Compile one strictly admitted rotary profile into a C++20 build-tree header.

The existing validator owns JSON/schema, evidence, units and physical admission.
This compiler introduces no physical values. Every runtime double is emitted as
an exact hexadecimal binary64 literal, including the sign of zero. Authoring
prose remains in the source JSON; its exact bytes are identified by SHA-256.

Public API: compile_header(path) returns (ASCII bytes, identity mapping);
compile_profile(input_path, output_path) atomically publishes those bytes and
returns the identity mapping. The output parent must already exist. A rejected
input or failed write preserves any previous output. No temporary file survives
an ordinary failed write. All work belongs outside audio processing.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import stat
import sys
import tempfile

import validate_rotary_profile as admission


RotaryProfileError = admission.RotaryProfileError


def _cpp_string_literal(value: str) -> str:
    """Encode UTF-8 bytes with bounded, unambiguous C++ octal escapes.

    Three octal digits prevent a following digit from extending an escape;
    escaping question marks also makes the source independent of trigraphs.
    The emitted profile/model/contract identifiers are already restricted ASCII.
    """
    return '"' + "".join(
        chr(byte) if 32 <= byte <= 126 and byte not in (34, 63, 92)
        else f"\\{byte:03o}"
        for byte in value.encode("utf-8")
    ) + '"'


def compile_header(input_path: str | Path) -> tuple[bytes, dict[str, str]]:
    """Read the bounded source once, admit it, and build deterministic bytes."""
    authoring, digest = admission.load_profile_with_digest(input_path)
    profile = admission.normalized_profile(authoring)
    identity = {
        "profile_id": profile["profile_id"],
        "model_id": profile["model_id"],
        "contract_id": profile["contract_id"],
        "source_file_sha256": digest,
    }
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/compile_rotary_profile.py; do not edit.",
        "// Strictly admitted nominal research values; physical status: unmeasured.",
        '#include "hammond/RotaryTypes.h"',
        "#include <limits>",
        "#include <string_view>",
        "",
        "namespace hammond::rotary::generated {",
        "",
        "static_assert(sizeof(double) == 8 && std::numeric_limits<double>::is_iec559",
        "              && std::numeric_limits<double>::digits == 53",
        "              && std::numeric_limits<double>::max_exponent == 1024,",
        '              "The rotary profile requires IEEE-754 binary64 doubles.");',
        "",
    ]
    for cpp_name, key in (
        ("kProfileId", "profile_id"),
        ("kProfileSha256", "source_file_sha256"),
        ("kModelId", "model_id"),
        ("kContractId", "contract_id"),
    ):
        lines.append(f"inline constexpr std::string_view {cpp_name} = "
                     f"{_cpp_string_literal(identity[key])};")
    lines.extend([
        "",
        "static_assert(kModelId == ::hammond::rotary::kModelId);",
        "static_assert(kContractId == ::hammond::rotary::kNumericalContractId);",
        "",
        "[[nodiscard]] inline Profile nominal_profile() noexcept {",
        "    Profile profile{};",
    ])
    for index, name in enumerate(("horn", "drum")):
        rotor = profile["rotors"][name]
        member = f"profile.rotors[{index}]"
        origin = ", ".join(value.hex() for value in rotor["origin_m"])
        lines.append(f"    {member}.origin_m = {{{origin}}};")
        lines.append(f"    {member}.radius_m = {rotor['radius_m'].hex()};")
        for field in ("slow_rad_s", "fast_rad_s", "tau_up_s", "tau_down_s"):
            lines.append(f"    {member}.motion.{field} = {rotor['motion'][field].hex()};")
        lines.append(f"    {member}.motion.direction = {rotor['motion']['direction']};")
        for field in ("initial_phase_rad", "initial_speed_rad_s"):
            lines.append(f"    {member}.{field} = {rotor[field].hex()};")
        command = {"chorale": "Chorale", "tremolo": "Tremolo"}[rotor["initial_command"]]
        lines.append(f"    {member}.initial_command = SpeedCommand::{command};")
    for index, microphone in enumerate(profile["microphones"]):
        position = ", ".join(value.hex() for value in microphone["position_m"])
        lines.append(f"    profile.microphones[{index}].position_m = {{{position}}};")
    for field in ("sound_speed_m_s", "reference_distance_m"):
        lines.append(f"    profile.{field} = {profile[field].hex()};")
    lines.extend([
        "    return profile;",
        "}",
        "",
        "} // namespace hammond::rotary::generated",
        "",
    ])
    return "\n".join(lines).encode("ascii"), identity


def _admit_output(input_path: str | Path, output_path: str | Path) -> Path:
    if not isinstance(output_path, (str, Path)):
        raise RotaryProfileError("output: path must be a string or pathlib.Path")
    source, destination = Path(input_path), Path(output_path)
    try:
        if source.resolve() == destination.resolve():
            raise RotaryProfileError("output: input and output paths must differ")
        try:
            metadata = destination.lstat()
        except FileNotFoundError:
            return destination
        if not stat.S_ISREG(metadata.st_mode):
            raise RotaryProfileError("output: existing destination must be a regular file")
        if os.path.samefile(source, destination):
            raise RotaryProfileError("output: input and output must not identify the same file")
    except (OSError, RuntimeError, ValueError) as error:
        if isinstance(error, RotaryProfileError):
            raise
        raise RotaryProfileError(f"output: {error}") from error
    return destination


def _atomic_write(destination: Path, payload: bytes) -> None:
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="wb", dir=destination.parent,
                                         prefix=f".{destination.name}.",
                                         suffix=".tmp", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, destination)
        temporary = None
    except (OSError, ValueError) as error:
        raise RotaryProfileError(f"output: cannot publish {destination}: {error}") from error
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def compile_profile(input_path: str | Path, output_path: str | Path) -> dict[str, str]:
    payload, identity = compile_header(input_path)
    destination = _admit_output(input_path, output_path)
    _atomic_write(destination, payload)
    return identity


class _Parser(argparse.ArgumentParser):
    def error(self, message: str) -> None:
        raise RotaryProfileError(f"arguments: {message}")


def main(argv: list[str] | None = None) -> int:
    try:
        parser = _Parser(description=__doc__, allow_abbrev=False)
        parser.add_argument("--input", type=Path, required=True)
        parser.add_argument("--output", type=Path, required=True)
        args = parser.parse_args(argv)
        identity = compile_profile(args.input, args.output)
        print(json.dumps({"status": "compiled", **identity}, sort_keys=True))
        return 0
    except RotaryProfileError as error:
        print(json.dumps({"status": "rejected", "error": str(error)}, sort_keys=True))
        return 2


if __name__ == "__main__":
    sys.exit(main())
