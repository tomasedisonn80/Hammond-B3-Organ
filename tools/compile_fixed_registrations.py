#!/usr/bin/env python3
"""Compile the frozen admitted chapel registrations into immutable native data.

The strict documentary compiler admits the authoring JSON and both independent
CSV readings first. This runtime model additionally requires the authoring file's
frozen raw-byte SHA-256. No source parsing or filesystem work enters the engine.
compile_fixed_registrations returns deterministic C++ header text without writes;
write_fixed_registrations publishes that text atomically in an existing directory.
Failures raise FixedRegistrationCompileError and preserve any previous output.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from types import ModuleType
from typing import Any


def _load_chapel_source() -> ModuleType:
    """Execute the adjacent admission source without a timestamp-bytecode cache.

    CMake tracks nanosecond source changes, while Python's ordinary timestamp
    cache can reuse an older same-size module edited within the same second.
    Read and compile one exact source payload so generation uses the dependency
    bytes selected by this checkout, even when an older .pyc remains present.
    The strict compiler's imports are all from the Python standard library.
    """
    path = Path(__file__).resolve().with_name("compile_chapel_presets.py")
    source = path.read_bytes()
    module = ModuleType("_hammond_fixed_registration_chapel_source")
    module.__file__ = str(path)
    exec(compile(source, str(path), "exec"), module.__dict__)
    return module


chapel = _load_chapel_source()


FROZEN_AUTHORING_SHA256 = "c9f1dd2d4287448325834f66f3998f4c32a41f84bc7ec7216e7b72ebcbf722cf"
MAX_OUTPUT_BYTES = chapel.MAX_OUTPUT_BYTES
FixedRegistrationCompileError = chapel.ChapelCompileError


def compile_fixed_registrations(input_path: str | Path, review_a_path: str | Path,
                                review_b_path: str | Path) -> str:
    """Admit all three original inputs, then return the fixed native table."""
    # Use the hash of the bytes actually admitted by the existing compiler;
    # reopening the authoring file here would introduce a second-read race.
    catalog = json.loads(chapel.compile_chapel_presets(
        input_path, review_a_path, review_b_path))
    if catalog["inputs"]["authoring"]["sha256"] != FROZEN_AUTHORING_SHA256:
        raise FixedRegistrationCompileError(
            "authoring raw SHA-256 differs from the frozen fixed-registration model")

    lines = [
        "// Generated by compile_fixed_registrations.py; do not edit.",
        "// Atlas page 122 documentary tap indices, not measured loaded gains.",
        "// Both independent CSV readings and the exact authoring bytes were admitted.",
        "#pragma once", "", '#include "hammond/FixedRegistration.h"', "",
        "namespace hammond::generated {", "",
        f'inline constexpr std::string_view kFixedRegistrationCatalogId = "{catalog["model_id"]}";',
        f'inline constexpr std::string_view kFixedRegistrationCatalogRawSha256 = "{FROZEN_AUTHORING_SHA256}";',
        "", "static_assert(kManualCount == 2 && kDrawbarCount == 9 && kFixedRegistrationCount == 9);",
        "", "inline constexpr std::array<std::array<FixedRegistrationPositions, kFixedRegistrationCount>,",
        "                            kManualCount> kFixedRegistrationPositions{{",
    ]
    for manual_index, manual in enumerate(("upper", "lower")):
        lines.append(f"    {{{{ // {manual}")
        for row in catalog["registrations"][manual_index * 9:(manual_index + 1) * 9]:
            positions = ", ".join(row["drawbars"])
            lines.append(f'        FixedRegistrationPositions{{{positions}}}, // {row["preset_key"]}')
        lines.append("    }},")
    lines.extend(("}};", "", "} // namespace hammond::generated", ""))
    text = "\n".join(lines)
    if len(text.encode("utf-8")) > MAX_OUTPUT_BYTES:
        raise FixedRegistrationCompileError("compiled fixed-registration header exceeds its byte bound")
    return text


def write_fixed_registrations(output: str | Path, text: str,
                              inputs: tuple[str | Path, ...]) -> None:
    """Reuse strict catalog publication, including all input-alias protections."""
    chapel.write_compiled_catalog(output, text, inputs)


class _Once(argparse.Action):
    def __call__(self, parser: argparse.ArgumentParser, namespace: argparse.Namespace,
                 values: Any, option_string: str | None = None) -> None:
        if getattr(namespace, self.dest, None) is not None:
            parser.error(f"{option_string}: may be supplied only once")
        setattr(namespace, self.dest, values)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], allow_abbrev=False)
    for name, description in (
        ("input", "frozen documentary authoring JSON"),
        ("review-a", "frozen independent reading A CSV"),
        ("review-b", "frozen independent reading B CSV"),
        ("output", "generated immutable native header"),
    ):
        parser.add_argument("--" + name, required=True, action=_Once, type=Path, help=description)
    args = parser.parse_args(argv)
    try:
        inputs = (args.input, args.review_a, args.review_b)
        text = compile_fixed_registrations(*inputs)
        write_fixed_registrations(args.output, text, inputs)
    except (FixedRegistrationCompileError, OSError) as error:
        print(f"fixed-registration compile error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
