#!/usr/bin/env python3
"""Admit exact decorative crops and emit a bounded, dependency-free RGB header.

The default build path uses only the Python standard library. Pillow is imported
only by explicit --verify-source and --extract-to authoring operations.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import platform
import sys
import tempfile
import zlib


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = ROOT / "assets/standalone/reference/manifest.json"
DEFAULT_SOURCE = ROOT / "docs/design/atlas-cover-reference.jpg"
MANIFEST_SHA256 = "bf1bec09c0dd15d09ab0129f950ccb5370532f92cb9217e347ba69e96d24bc87"
MAX_MANIFEST_BYTES = 16 * 1024
MAX_SOURCE_BYTES = 512 * 1024
MAX_PACKED_BYTES = 512 * 1024
MAX_PIXEL_BYTES = 1024 * 1024
MAX_HEADER_BYTES = 6 * 1024 * 1024


class ReferenceArtError(ValueError):
    """The frozen source, crop, byte or output identity was not satisfied."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def bounded_read(path: Path, maximum: int) -> bytes:
    if not path.is_file():
        raise ReferenceArtError(f"input is not a regular file: {path}")
    with path.open("rb") as stream:
        raw = stream.read(maximum + 1)
    if not raw or len(raw) > maximum:
        raise ReferenceArtError(f"input must contain 1..{maximum} bytes: {path}")
    return raw


def require_identity(raw: bytes, size: int, digest: str, name: str) -> None:
    if len(raw) != size or sha256(raw) != digest:
        raise ReferenceArtError(f"{name} byte count or SHA-256 changed")


def read_manifest(path: Path) -> tuple[dict, bytes]:
    raw = bounded_read(path, MAX_MANIFEST_BYTES)
    # Pin the reviewed crop/decoder/pixel identities together. Replacing both a
    # blob and its manifest hash cannot silently bless new source artwork.
    if sha256(raw) != MANIFEST_SHA256:
        raise ReferenceArtError("reference manifest SHA-256 changed")
    manifest = json.loads(raw)
    if manifest["schema_version"] != 1 or len(manifest["assets"]) != 3:
        raise ReferenceArtError("unsupported reference manifest")
    return manifest, raw


def read_source(path: Path, manifest: dict) -> bytes:
    raw = bounded_read(path, MAX_SOURCE_BYTES)
    source = manifest["source"]
    require_identity(raw, source["bytes"], source["sha256"], "source JPEG")
    return raw


def decode_gzip(packed: bytes, expected: int) -> bytes:
    if not 0 < expected <= MAX_PIXEL_BYTES:
        raise ReferenceArtError("decoded pixel bound is invalid")
    # max_length bounds allocation even for hostile DEFLATE input. eof checks
    # the gzip CRC and size trailer; unused_data rejects extra gzip members.
    decoder = zlib.decompressobj(16 + zlib.MAX_WBITS)
    try:
        pixels = decoder.decompress(packed, expected + 1)
    except zlib.error as exc:
        raise ReferenceArtError(f"invalid gzip pixels: {exc}") from exc
    if (len(pixels) != expected or not decoder.eof or
            decoder.unconsumed_tail or decoder.unused_data):
        raise ReferenceArtError("gzip must contain one complete, exactly sized pixel stream")
    return pixels


def read_assets(manifest: dict, directory: Path) -> list[tuple[dict, bytes]]:
    decoded = []
    total = 0
    for asset in manifest["assets"]:
        # These fields are already protected by the manifest lock; retain the
        # local size checks so the native output contract remains explicit.
        width, height = asset["width"], asset["height"]
        expected = width * height * 3
        if (width <= 0 or height <= 0 or asset["pitch"] != width * 3 or
                asset["pixel_bytes"] != expected):
            raise ReferenceArtError(f"invalid RGB24 extent: {asset['name']}")
        total += expected
        if total > MAX_PIXEL_BYTES:
            raise ReferenceArtError("combined reference pixels exceed the build bound")
        packed = bounded_read(directory / asset["file"], MAX_PACKED_BYTES)
        require_identity(packed, asset["bytes"], asset["sha256"], asset["file"])
        pixels = decode_gzip(packed, expected)
        require_identity(pixels, expected, asset["pixel_sha256"], asset["name"] + " pixels")
        decoded.append((asset, pixels))
    return decoded


def make_header(manifest: dict, decoded: list[tuple[dict, bytes]]) -> bytes:
    lines = [
        "// Generated by tools/compile_reference_art.py; do not edit.",
        "// Decorative source crops only; never an application screenshot or control surface.",
        f"// Source JPEG SHA-256: {manifest['source']['sha256']}",
        f"// Manifest SHA-256: {MANIFEST_SHA256}",
        "#pragma once", "", "#include <cstddef>", "#include <cstdint>", "",
        "namespace hammond::standalone::reference_art {", "",
        "// RGB24 bytes, top row first; pitch has no alignment padding.",
        "// Use SDL_PIXELFORMAT_RGB24 and upload only from the main/UI thread.",
        "struct RgbImage {", "    int width;", "    int height;", "    int pitch;",
        "    const std::uint8_t* pixels;", "    std::size_t byte_count;", "};", "",
    ]
    for asset, pixels in decoded:
        symbol = asset["cpp_symbol"]
        lines.extend([
            f"// {asset['name']}: source (x, y, w, h) = {tuple(asset['source_rect'])}",
            f"// RGB SHA-256: {asset['pixel_sha256']}",
            f"inline constexpr std::uint8_t {symbol}Pixels[] = {{",
        ])
        lines.extend("    " + ", ".join(f"0x{byte:02x}" for byte in pixels[start:start + 16]) + ","
                     for start in range(0, len(pixels), 16))
        lines.extend([
            "};",
            f"inline constexpr RgbImage {symbol}{{",
            f"    {asset['width']}, {asset['height']}, {asset['pitch']},",
            f"    {symbol}Pixels, sizeof({symbol}Pixels)}};",
            f"static_assert(sizeof({symbol}Pixels) == {asset['pixel_bytes']});", "",
        ])
    lines.extend([
        f"inline constexpr std::size_t kTotalPixelBytes = {sum(len(p) for _, p in decoded)};",
        "", "} // namespace hammond::standalone::reference_art", "",
    ])
    header = "\n".join(lines).encode("ascii")
    if len(header) > MAX_HEADER_BYTES:
        raise ReferenceArtError("generated header exceeds the build bound")
    return header


def write_atomic(path: Path, raw: bytes, protected: set[Path]) -> bool:
    if path.resolve() in protected:
        raise ReferenceArtError("output must not replace a compiler input")
    if path.is_symlink() or (path.exists() and not path.is_file()):
        raise ReferenceArtError("output must be a regular file, not a symlink or directory")
    if path.exists():
        with path.open("rb") as stream:
            if stream.read(len(raw) + 1) == raw:
                return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(prefix=".reference-art-", dir=path.parent,
                                         delete=False) as stream:
            temporary = stream.name
            stream.write(raw)
        os.replace(temporary, path)
        temporary = None
    finally:
        if temporary is not None:
            os.unlink(temporary)
    return True


def source_pixels(source: bytes, manifest: dict) -> tuple[list[bytes], dict]:
    try:
        import PIL
        from PIL import Image, features
    except ImportError as exc:
        raise ReferenceArtError(
            "source verification/extraction needs Pillow; ordinary header compilation does not") from exc
    versions = {
        "tool": "tools/compile_reference_art.py", "tool_version": 1,
        "python": platform.python_version(), "pillow": PIL.__version__,
        "libjpeg_api": features.version("jpg"),
        "libjpeg_turbo": features.version("libjpeg_turbo"),
        "zlib_compile": zlib.ZLIB_VERSION, "zlib_runtime": zlib.ZLIB_RUNTIME_VERSION,
    }
    with Image.open(io.BytesIO(source)) as opened:
        if opened.format != "JPEG" or opened.size != (1672, 941):
            raise ReferenceArtError("unexpected source image format or dimensions")
        opened.load()
        rgb = opened.convert("RGB")
    expected = manifest["source"]
    require_identity(rgb.tobytes(), expected["width"] * expected["height"] * 3,
                     expected["decoded_rgb_sha256"], "decoded source RGB")
    crops = []
    for asset in manifest["assets"]:
        x, y, width, height = asset["source_rect"]
        crop = rgb.crop((x, y, x + width, y + height)).tobytes()
        require_identity(crop, asset["pixel_bytes"], asset["pixel_sha256"],
                         asset["name"] + " source crop")
        crops.append(crop)
    return crops, versions


def canonical_gzip(pixels: bytes) -> bytes:
    output = io.BytesIO()
    # GzipFile fixes the OS byte at 255; gzip.compress varies by Python version.
    with gzip.GzipFile(fileobj=output, mode="wb", filename="", compresslevel=9, mtime=0) as stream:
        stream.write(pixels)
    return output.getvalue()


def run(args: argparse.Namespace) -> str:
    manifest, manifest_bytes = read_manifest(args.input)
    source = read_source(args.source, manifest)
    protected = {args.input.resolve(), args.source.resolve(), Path(__file__).resolve()}
    protected.update((args.input.parent / a["file"]).resolve() for a in manifest["assets"])
    if args.extract_to is not None:
        crops, versions = source_pixels(source, manifest)
        if versions != manifest["authoring"]:
            raise ReferenceArtError(f"authoring toolchain differs from the frozen manifest: {versions}")
        outputs = []
        for asset, pixels in zip(manifest["assets"], crops):
            packed = canonical_gzip(pixels)
            require_identity(packed, asset["bytes"], asset["sha256"], asset["file"])
            outputs.append((args.extract_to / asset["file"], packed))
        # All identities are admitted before writing any authoring output.
        for path, packed in outputs:
            write_atomic(path, packed, protected)
        write_atomic(args.extract_to / "manifest.json", manifest_bytes, protected)
        return "Extracted 3 exact source crops with identical gzip and manifest bytes"
    decoded = read_assets(manifest, args.input.parent)
    if args.verify_source:
        crops, versions = source_pixels(source, manifest)
        if any(crop != pixels for crop, (_, pixels) in zip(crops, decoded)):
            raise ReferenceArtError("decoded decorative bytes differ from original source crop")
        return "Verified exact source-pixel equality for 3 crops; decoder " + json.dumps(versions, sort_keys=True)
    if args.output is not None:
        header = make_header(manifest, decoded)
        changed = write_atomic(args.output, header, protected)
        return (f"{'Wrote' if changed else 'Unchanged'} RGB header: {len(header)} bytes; "
                f"SHA-256 {sha256(header)}; 3 images, {sum(len(p) for _, p in decoded)} RGB bytes")
    return (f"Verified 3 decorative assets and source; {sum(len(p) for _, p in decoded)} RGB bytes; "
            f"manifest SHA-256 {MANIFEST_SHA256}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_MANIFEST,
                        help="frozen manifest; blobs are read from its directory")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE,
                        help="original JPEG, byte-verified without decoding during normal builds")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--output", type=Path, help="generated C++ header, normally in the build tree")
    mode.add_argument("--verify-only", action="store_true", help="verify source/blob/pixel identities using stdlib")
    mode.add_argument("--verify-source", action="store_true", help="also decode and compare source pixels; needs Pillow")
    mode.add_argument("--extract-to", type=Path, help="reauthor identical locked assets in a separate directory; needs Pillow")
    args = parser.parse_args(argv)
    try:
        print(run(args))
    except (ReferenceArtError, OSError, UnicodeError, json.JSONDecodeError) as exc:
        print(f"Reference art error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
