    def test_fdopen_failure_closes_the_acquired_descriptor(self):
        original_open = os.open
        acquired = []

        def acquire(*args, **kwargs):
            descriptor = original_open(*args, **kwargs)
            acquired.append(descriptor)
            return descriptor

        try:
            with mock.patch.object(CHECKER.os, "open", side_effect=acquire), mock.patch.object(
                CHECKER.os, "fdopen", side_effect=OSError("controlled fdopen failure")
            ):
                self.assert_failure(CHECKER.check(self.root), "controlled fdopen failure")
            self.assertEqual(len(acquired), 1)
            with self.assertRaises(OSError):
                os.fstat(acquired[0])
        finally:
            for descriptor in acquired:
                try:
                    os.close(descriptor)
                except OSError:
                    pass

    def test_windows_reparse_metadata_rejects_parent_and_leaf_aliases(self):
        original_lstat = Path.lstat
        # Controlled Windows metadata on real inside-repository files/directories
        # exercises the junction/alias guard on runners without Windows junctions.
        for marked in (self.root / "docs/development", self.root / "owned",
                       self.root / "owned/01.txt"):
            def mark_reparse(path, *args, **kwargs):
                metadata = original_lstat(path, *args, **kwargs)
                if path == marked:
                    return SimpleNamespace(st_mode=metadata.st_mode, st_size=metadata.st_size,
                                           st_file_attributes=0x400)
                return metadata

            with self.subTest(component=marked), mock.patch.object(
                CHECKER.Path, "lstat", autospec=True, side_effect=mark_reparse
            ):
                self.assert_failure(CHECKER.check(self.root), "Windows reparse points are not allowed")


