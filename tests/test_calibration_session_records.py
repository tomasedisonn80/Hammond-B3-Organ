ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / "tools/check_calibration_session.py"
SPEC = importlib.util.spec_from_file_location("calibration_session_checker", TOOL)
CHECKER = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECKER)
SESSION_PATH = Path("docs/development/2026-11-13-calibration")


class CalibrationSessionRecordsTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="hammond-calibration-records-")
        self.addCleanup(temporary.cleanup)
        self.temporary = Path(temporary.name)
        self.root = self.temporary / "résumé 音"
        self.session = self.root / SESSION_PATH
        self.session.mkdir(parents=True)
        # This fixture is authored independently, never copied from a live ledger
        # or generated by the checker. These names are synthetic test identities.
        self.manifest = {
            "schema_version": 1,
            "session_id": "2026-11-13-calibration",
            "baseline_commit": "38c1fac949368fa54bd86c6c00a5997a73480f5e",
            "requested_agents": 60, "requested_waves": 10, "concurrency": 3,
            "assignments": [
                {"assignment": number, "wave": (number - 1) // 6 + 1,
                 "state": "planned", "agent": None,
                 "scope": "Synthetic planned fixture; no actual worker is represented.",
                 "note": None, "owned_files": []}
                for number in range(1, 61)
            ],
        }
        for number in range(1, 7):
            self.dispatch(number, "complete")
        self.dispatch(7, "running")
        self.dispatch(8, "running")
        self.save()

    def dispatch(self, number, state):
        row = self.manifest["assignments"][number - 1]
        row.update(state=state, agent=f"/root/cal_w{(number - 1) // 6 + 1}_a{number:02d}",
                   note=f"{number:02d}-fixture.md")
        row["owned_files"] = [(SESSION_PATH / row["note"]).as_posix(), f"owned/{number:02d}.txt"]
        if state == "complete":
            self.write_note(number)
            owned = self.root / row["owned_files"][1]
            owned.parent.mkdir(exist_ok=True)
            owned.write_text("Independent synthetic owned-file fixture.\n", encoding="utf-8")

    def write_note(self, number, text=None):
        row = self.manifest["assignments"][number - 1]
        if text is None:
            text = (
                f"# Synthetic retained evidence for assignment {number}\n\n"
                f"Canonical fixture worker: `{row['agent']}`.\n\n"
                "This independent fixture checks record consistency only. It represents no "
                "actual dispatched agent, hardware acquisition, numerical acceptance or "
                "publication. The fixture owns its note and a small regular text file. "
                "Verification is performed by the unittest caller in a temporary directory.\n"
            )
        (self.session / row["note"]).write_text(text, encoding="utf-8")

    def save(self):
        (self.session / "assignments.json").write_text(
            json.dumps(self.manifest, indent=2) + "\n", encoding="utf-8")

    def check(self, expected_complete=None):
        self.save()
        return CHECKER.check(self.root, expected_complete)

    def assert_failure(self, result, message=None):
        self.assertEqual(result["status"], "failed", result)
        self.assertGreater(result["error_count"], 0)
        if message:
            self.assertIn(message, "\n".join(result["errors"]))

    def cli(self, *args):
        return subprocess.run([sys.executable, "-B", str(TOOL), "--repo", str(self.root), *args],
                              capture_output=True, text=True, timeout=15, check=False)

    def symlink(self, destination, link, directory=False):
        try:
            link.symlink_to(destination, target_is_directory=directory)
        except (NotImplementedError, OSError) as exc:
            self.skipTest(f"symbolic links unavailable on this runner: {exc}")

    def test_valid_partial_counts_and_explicit_claim_limits(self):
        before = (self.session / "assignments.json").read_bytes()
        result = CHECKER.check(self.root, 6)
        self.assertEqual(result["status"], "passed", result)
        self.assertEqual(result["counts"], {"planned": 52, "running": 2, "complete": 6})
        self.assertEqual(result["distinct_actual_agents"], 8)
        self.assertEqual(result["completed_waves"], [1])
        self.assertEqual(result["scope"], "retained_accounting_consistency_only")
        self.assertIs(result["external_dispatch_attested"], False)
        self.assertEqual(result["physical_fidelity"], "not_established")
        self.assertEqual((self.session / "assignments.json").read_bytes(), before)

    def test_all_planned_has_zero_dispatched_even_with_unassigned_notes(self):
        for row in self.manifest["assignments"]:
            row.update(state="planned", agent=None, note=None, owned_files=[])
        result = self.check(0)
        self.assertEqual(result["status"], "passed", result)
        self.assertEqual(result["counts"], {"planned": 60, "running": 0, "complete": 0})
        self.assertEqual(result["distinct_actual_agents"], 0)
        self.assertEqual(result["completed_waves"], [])

    def test_full_sixty_requires_all_actual_records_and_ten_complete_waves(self):
        for number in range(7, 61):
            self.dispatch(number, "complete")
        result = self.check(60)
        self.assertEqual(result["status"], "passed", result)
        self.assertEqual(result["counts"], {"planned": 0, "running": 0, "complete": 60})
        self.assertEqual(result["distinct_actual_agents"], 60)
        self.assertEqual(result["completed_waves"], list(range(1, 11)))
        self.manifest["assignments"][-1]["state"] = "running"
        self.assert_failure(self.check(60), "observed 59")

    def test_expected_complete_is_exact_not_a_minimum(self):
        for count in (0, 5, 7, 60):
            with self.subTest(count=count):
                self.assert_failure(self.check(count), f"expected {count} completed assignments, observed 6")
        for value in (True, False, -1, 61, 6.0, "6", [], {}):
            with self.subTest(value=value):
                self.assert_failure(self.check(value), "integer in 0..60")

    def test_running_evidence_and_other_sessions_do_not_promote_completion(self):
        for number in (7, 8):
            self.write_note(number)
        older = self.root / "docs/development/2026-11-13-rotary"
        older.mkdir()
        (older / "assignments.json").write_text('{"complete":60}', encoding="utf-8")
        (self.session / "60-unassigned.md").write_text("Unassigned artifact\n" * 30, encoding="utf-8")
        result = self.check(6)
        self.assertEqual(result["status"], "passed", result)
        self.assertEqual(result["distinct_actual_agents"], 8)
        self.assertEqual(result["counts"]["complete"], 6)

    def test_cli_json_success_failure_and_human_output(self):
        result = self.cli("--json", "--expected-complete", "6")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout)["counts"]["complete"], 6)
        self.assertEqual(result.stderr, "")
        for count in ("5", "60", "-1", "61"):
            result = self.cli("--json", "--expected-complete", count)
            self.assertEqual(result.returncode, 1, result)
            self.assertEqual(json.loads(result.stdout)["status"], "failed")
            self.assertEqual(result.stderr, "")
        result = self.cli("--expected-complete", "60")
        self.assertEqual(result.returncode, 1)
        self.assertIn("Calibration retained accounting: failed", result.stdout)
        self.assertIn("observed 6", result.stderr)
        self.assertEqual(self.cli("--expected-complete", "6.0").returncode, 2)

    def test_exact_manifest_schema_and_fixed_session_metadata(self):
        original = copy.deepcopy(self.manifest)
        cases = (("schema_version", True), ("schema_version", 1.0), ("schema_version", 2),
                 ("session_id", "2026-11-13-rotary"), ("session_id", None),
                 ("baseline_commit", "38c1fac"), ("baseline_commit", "a" * 40),
                 ("requested_agents", 59), ("requested_agents", "60"),
                 ("requested_waves", 9), ("requested_waves", 10.0),
                 ("concurrency", True), ("concurrency", 4), ("concurrency", 3.0),
                 ("assignments", None), ("assignments", {}))
        for key, value in cases:
            with self.subTest(key=key, value=value):
                self.manifest = copy.deepcopy(original)
                self.manifest[key] = value
                self.assert_failure(self.check())
        for remove in (True, False):
            self.manifest = copy.deepcopy(original)
            if remove:
                del self.manifest["concurrency"]
            else:
                self.manifest["complete"] = 60
            self.assert_failure(self.check(), "manifest members")

    def test_missing_invalid_and_duplicate_json_is_reported_without_traceback(self):
        path = self.session / "assignments.json"
        original = path.read_text(encoding="utf-8")
        cases = ("{", "[]", "null", "true", "[" * 2000 + "]" * 2000,
                 original.replace('"schema_version": 1', '"schema_version": 1, "schema_version": 1'),
                 original.replace('"assignment": 1', '"assignment": 1, "assignment": 1', 1),
                 original.replace('"assignment": 1', '"assignment": NaN', 1),
                 original.replace('"assignment": 1', '"assignment": Infinity', 1),
                 original.replace('"assignment": 1', '"assignment": -Infinity', 1))
        for text in cases:
            with self.subTest(text=text[:40]):
                path.write_text(text, encoding="utf-8")
                self.assert_failure(CHECKER.check(self.root))
        path.write_bytes(b"\xff")
        self.assert_failure(CHECKER.check(self.root), "cannot read manifest")
        path.unlink()
        self.assert_failure(CHECKER.check(self.root), "cannot read manifest")
        self.assert_failure(CHECKER.check(self.root / "missing"), "cannot read manifest")

